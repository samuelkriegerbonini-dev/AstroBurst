#[derive(Debug, Clone, Copy, PartialEq)]
pub struct OfflineObject {
    pub designations: &'static [&'static str],
    pub ra_deg: f64,
    pub dec_deg: f64,
}

const fn object(designations: &'static [&'static str], ra_deg: f64, dec_deg: f64) -> OfflineObject {
    OfflineObject {
        designations,
        ra_deg,
        dec_deg,
    }
}

const CATALOGUE_PREFIXES: [(&str, &str); 6] = [
    ("MESSIER", "M"),
    ("CALDWELL", "C"),
    ("NGC", "NGC"),
    ("IC", "IC"),
    ("M", "M"),
    ("C", "C"),
];
const NUMBER_SEPARATORS: [u8; 3] = [b' ', b'_', b'-'];
const MAX_CATALOGUE_DIGITS: usize = 4;

fn catalogue_number(rest: &[u8]) -> Option<u32> {
    let start = rest.iter().position(|b| !NUMBER_SEPARATORS.contains(b))?;
    let digits = rest[start..]
        .iter()
        .take_while(|b| b.is_ascii_digit())
        .count();
    if digits == 0 || digits > MAX_CATALOGUE_DIGITS {
        return None;
    }
    std::str::from_utf8(&rest[start..start + digits])
        .ok()?
        .parse()
        .ok()
        .filter(|&number| number > 0)
}

pub fn designation(text: &str) -> Option<String> {
    let upper = text.to_ascii_uppercase();
    let bytes = upper.as_bytes();
    (0..bytes.len())
        .filter(|&start| start == 0 || !bytes[start - 1].is_ascii_alphanumeric())
        .find_map(|start| {
            CATALOGUE_PREFIXES.iter().find_map(|(prefix, short)| {
                let rest = bytes[start..].strip_prefix(prefix.as_bytes())?;
                catalogue_number(rest).map(|number| format!("{short} {number}"))
            })
        })
}

pub fn resolve(text: &str) -> Option<(String, &'static OfflineObject)> {
    let wanted = designation(text)?;
    let found = OFFLINE_OBJECTS
        .iter()
        .find(|object| object.designations.contains(&wanted.as_str()))?;
    Some((wanted, found))
}

