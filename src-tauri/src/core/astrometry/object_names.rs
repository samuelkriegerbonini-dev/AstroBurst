    #[test]
    fn designation_reads_catalogue_prefixes_in_any_spelling() {
        for (text, expected) in [
            ("M31", "M 31"),
            ("M 31", "M 31"),
            ("m_31 panel 2", "M 31"),
            ("Messier 31", "M 31"),
            ("M031", "M 31"),
            ("NGC7000", "NGC 7000"),
            ("NGC 7000 North America", "NGC 7000"),
            ("Light_NGC-6992_300s", "NGC 6992"),
            ("IC 1805 Heart", "IC 1805"),
            ("IC1396A", "IC 1396"),
            ("C 20", "C 20"),
            ("Caldwell 20", "C 20"),
            ("M31 and M110", "M 31"),
        ] {
            assert_eq!(designation(text).as_deref(), Some(expected), "{text:?}");
        }
    }

    #[test]
    fn designation_ignores_prefixes_inside_words_and_other_catalogues() {
        for text in [
            "",
            "TIC 12345678",
            "HD 209458",
            "C/2023 A3",
            "Sh2-155",
            "LDN 1235",
            "M",
            "NGC",
            "M 0",
            "Flat",
            "PIC 5",
        ] {
            assert_eq!(designation(text), None, "{text:?}");
        }
    }
