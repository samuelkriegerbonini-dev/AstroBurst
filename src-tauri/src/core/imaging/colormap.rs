use std::sync::LazyLock;

use image::{codecs::png::PngEncoder, ColorType, ImageEncoder};

use crate::types::constants::LUT_SIZE;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Colormap {
    Gray,
    Viridis,
    Inferno,
    Magma,
    Plasma,
    Cividis,
    Heat,
    Cool,
    Rainbow,
}

impl Colormap {
    pub const ALL: [Colormap; 9] = [
        Colormap::Gray,
        Colormap::Viridis,
        Colormap::Inferno,
        Colormap::Magma,
        Colormap::Plasma,
        Colormap::Cividis,
        Colormap::Heat,
        Colormap::Cool,
        Colormap::Rainbow,
    ];

    pub fn from_name(name: &str) -> Result<Self, String> {
        match name.trim().to_ascii_lowercase().as_str() {
            "gray" | "grey" => Ok(Colormap::Gray),
            "viridis" => Ok(Colormap::Viridis),
            "inferno" => Ok(Colormap::Inferno),
            "magma" => Ok(Colormap::Magma),
            "plasma" => Ok(Colormap::Plasma),
            "cividis" => Ok(Colormap::Cividis),
            "heat" => Ok(Colormap::Heat),
            "cool" => Ok(Colormap::Cool),
            "rainbow" => Ok(Colormap::Rainbow),
            other => Err(format!(
                "unknown colormap '{other}' (supported: gray, viridis, inferno, magma, plasma, cividis, heat, cool, rainbow)"
            )),
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Colormap::Gray => "gray",
            Colormap::Viridis => "viridis",
            Colormap::Inferno => "inferno",
            Colormap::Magma => "magma",
            Colormap::Plasma => "plasma",
            Colormap::Cividis => "cividis",
            Colormap::Heat => "heat",
            Colormap::Cool => "cool",
            Colormap::Rainbow => "rainbow",
        }
    }

    pub fn lut(self) -> &'static [[u8; 3]; 256] {
        match self {
            Colormap::Gray => &GRAY_LUT,
            Colormap::Viridis => &VIRIDIS_LUT,
            Colormap::Inferno => &INFERNO_LUT,
            Colormap::Magma => &MAGMA_LUT,
            Colormap::Plasma => &PLASMA_LUT,
            Colormap::Cividis => &CIVIDIS_LUT,
            Colormap::Heat => &HEAT_LUT,
            Colormap::Cool => &COOL_LUT,
            Colormap::Rainbow => &RAINBOW_LUT,
        }
    }

    pub fn lut_rgba(self) -> [u8; 1024] {
        let lut = self.lut();
        let mut out = [255u8; 1024];
        for (i, rgb) in lut.iter().enumerate() {
            out[i * 4..i * 4 + 3].copy_from_slice(rgb);
        }
        out
    }
}

pub fn lut_index(v: f32, invert: bool) -> usize {
    if !v.is_finite() {
        return 0;
    }
    let idx = (v.clamp(0.0, 1.0) * 255.0).round() as usize;
    if invert {
        LUT_SIZE - 1 - idx
    } else {
        idx
    }
}

pub fn apply_colormap(values: &[f32], colormap: Colormap) -> Vec<u8> {
    apply_colormap_inverted(values, colormap, false)
}

pub fn apply_colormap_inverted(values: &[f32], colormap: Colormap, invert: bool) -> Vec<u8> {
    let lut = colormap.lut();
    let mut out = Vec::with_capacity(values.len() * 3);
    for &v in values {
        out.extend_from_slice(&lut[lut_index(v, invert)]);
    }
    out
}

pub fn encode_png_rgb8(rgb: &[u8], width: usize, height: usize) -> anyhow::Result<Vec<u8>> {
    debug_assert_eq!(rgb.len(), width * height * 3, "rgb buffer size mismatch");
    let mut buf = Vec::with_capacity(width * height * 3);
    let encoder = PngEncoder::new_with_quality(
        std::io::Cursor::new(&mut buf),
        image::codecs::png::CompressionType::Fast,
        image::codecs::png::FilterType::Sub,
    );
    encoder.write_image(rgb, width as u32, height as u32, ColorType::Rgb8.into())?;
    Ok(buf)
}

