    #[test]
    fn perceptual_maps_have_non_decreasing_luminance() {
        for cmap in [
            Colormap::Viridis,
            Colormap::Inferno,
            Colormap::Magma,
            Colormap::Plasma,
            Colormap::Cividis,
        ] {
            let lut = cmap.lut();
            let lum = |c: &[u8; 3]| 0.299 * c[0] as f64 + 0.587 * c[1] as f64 + 0.114 * c[2] as f64;
            let mut prev = lum(&lut[0]);
            for (i, entry) in lut.iter().enumerate().skip(1) {
                let l = lum(entry);
                assert!(
                    l >= prev - 1.0,
                    "{} luminance drops at {i}: {l} < {prev}",
                    cmap.name()
                );
                prev = l;
            }
        }
    }
