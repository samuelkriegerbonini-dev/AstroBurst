fn piecewise_linear(knots: &[(f64, f64)], t: f64) -> f64 {
    let Some(&(t0, v0)) = knots.first() else {
        return 0.0;
    };
    if t <= t0 {
        return v0;
    }
    for pair in knots.windows(2) {
        let (ta, va) = pair[0];
        let (tb, vb) = pair[1];
        if t <= tb {
            if tb <= ta {
                return vb;
            }
            return va + (vb - va) * (t - ta) / (tb - ta);
        }
    }
    knots[knots.len() - 1].1
}

fn build_segment_lut(channels: &[Knots; 3]) -> [[u8; 3]; 256] {
    let mut lut = [[0u8; 3]; 256];
    for (i, entry) in lut.iter_mut().enumerate() {
        let t = i as f64 / 255.0;
        for (c, knots) in channels.iter().enumerate() {
            entry[c] = (piecewise_linear(knots, t).clamp(0.0, 1.0) * 255.0).round() as u8;
        }
    }
    lut
}

